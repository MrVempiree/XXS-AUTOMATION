import { useState, useRef, useCallback } from 'react';
import {
  Upload, Play, Square, Download, Copy, Check, ChevronDown, ChevronUp,
  AlertTriangle, CheckCircle, Clock, Loader, FileText, Trash2,
  Target, List, Activity, Filter, Eye, EyeOff
} from 'lucide-react';
import { toast } from 'sonner';
import { motion, AnimatePresence } from 'framer-motion';

// ── Types ──────────────────────────────────────────────────────────────────────
type UrlStatus = 'pending' | 'scanning' | 'done' | 'error' | 'skipped';
type ScanPhase = 'idle' | 'running' | 'done';

interface ParamHit {
  param: string;
  severity: string;
  hitsCount: number;
  injectionContext: string | null;
  bestPocUrl: string;
}

interface UrlResult {
  url: string;
  status: UrlStatus;
  error?: string;
  vulnerable: boolean;
  paramCount: number;
  vulnParams: ParamHit[];
  totalHits: number;
  duration: number;
  severity: string;
}

// ── Helpers ────────────────────────────────────────────────────────────────────
const SEV_RANK: Record<string, number> = { none: 0, low: 1, medium: 2, high: 3, critical: 4 };

function sevColor(s: string) {
  switch (s) {
    case 'critical': return 'text-red-500 border-red-500/30 bg-red-500/10';
    case 'high':     return 'text-orange-400 border-orange-400/30 bg-orange-400/10';
    case 'medium':   return 'text-yellow-400 border-yellow-400/30 bg-yellow-400/10';
    case 'low':      return 'text-blue-400 border-blue-400/30 bg-blue-400/10';
    default:         return 'text-muted-foreground border-border bg-secondary/30';
  }
}

function parseUrls(text: string): string[] {
  return text
    .split('\n')
    .map(l => l.trim())
    .filter(l => l && !l.startsWith('#'))
    .filter(l => {
      try { const u = new URL(l); return ['http:', 'https:'].includes(u.protocol); }
      catch { return false; }
    });
}

// ── SSE stream for one URL ─────────────────────────────────────────────────────
async function scanUrlStream(
  url: string,
  signal: AbortSignal,
  onEvent: (e: Record<string, unknown>) => void
): Promise<void> {
  const resp = await fetch('/api/scan/stream', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ url, timeout: 8000 }),
    signal,
  });
  if (!resp.ok || !resp.body) throw new Error('Scan failed');

  const reader = resp.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const chunks = buffer.split('\n\n');
    buffer = chunks.pop() ?? '';
    for (const chunk of chunks) {
      const line = chunk.trim();
      if (line.startsWith('data: ')) {
        try { onEvent(JSON.parse(line.slice(6))); } catch { /* skip */ }
      }
    }
  }
}

// ── Build CSV report ───────────────────────────────────────────────────────────
function buildCsv(results: UrlResult[]): string {
  const rows = [['URL', 'Vulnerable', 'Severity', 'Vuln Params', 'Total Hits', 'Duration (ms)', 'Param Details']];
  for (const r of results) {
    const params = r.vulnParams.map(p => `${p.param}(${p.severity})`).join(' | ');
    rows.push([r.url, r.vulnerable ? 'YES' : 'NO', r.severity, String(r.vulnParams.length), String(r.totalHits), String(r.duration), params]);
  }
  return rows.map(r => r.map(c => `"${c.replace(/"/g, '""')}"`).join(',')).join('\n');
}

function buildMarkdown(results: UrlResult[], stats: { total: number; vuln: number; duration: number }): string {
  const vulns = results.filter(r => r.vulnerable);
  const date = new Date().toISOString().split('T')[0];
  return `# XSS Bulk Scan Report
**Date:** ${date}
**Total URLs:** ${stats.total} | **Vulnerable:** ${stats.vuln} | **Duration:** ${(stats.duration / 1000).toFixed(1)}s

## Summary
| Metric | Value |
|--------|-------|
| URLs Scanned | ${stats.total} |
| Vulnerable | ${stats.vuln} |
| Safe | ${stats.total - stats.vuln} |
| Hit Rate | ${stats.total > 0 ? ((stats.vuln / stats.total) * 100).toFixed(1) : 0}% |

## Vulnerable URLs (${vulns.length})
${vulns.length === 0 ? '_None found_' : vulns.map(r => `
### ${r.url}
- **Severity:** ${r.severity.toUpperCase()}
- **Vulnerable Parameters:** ${r.vulnParams.map(p => `\`${p.param}\` (${p.severity})`).join(', ')}
- **Total Hits:** ${r.totalHits}
${r.vulnParams.filter(p => p.bestPocUrl).map(p => `- **PoC (${p.param}):** \`${p.bestPocUrl}\``).join('\n')}
`).join('\n')}

## All Results
| URL | Status | Severity | Vuln Params | Hits |
|-----|--------|----------|-------------|------|
${results.map(r => `| ${r.url} | ${r.vulnerable ? '🔴 VULN' : '✅ Safe'} | ${r.severity} | ${r.vulnParams.length} | ${r.totalHits} |`).join('\n')}

---
*Generated by ALCAME AUTOMATION — Bug Bounty Edition*
`;
}

// ── Main component ─────────────────────────────────────────────────────────────
export default function BulkScanner() {
  const [urlInput, setUrlInput]           = useState('');
  const [urls, setUrls]                   = useState<string[]>([]);
  const [results, setResults]             = useState<Map<string, UrlResult>>(new Map());
  const [phase, setPhase]                 = useState<ScanPhase>('idle');
  const [currentIdx, setCurrentIdx]       = useState(0);
  const [concurrency, setConcurrency]     = useState(3);
  const [expandedUrls, setExpandedUrls]   = useState<Set<string>>(new Set());
  const [filterVuln, setFilterVuln]       = useState(false);
  const [startTime, setStartTime]         = useState(0);
  const [elapsed, setElapsed]             = useState(0);
  const [copiedIdx, setCopiedIdx]         = useState<number | null>(null);

  const abortRef = useRef<AbortController | null>(null);
  const timerRef = useRef<ReturnType<typeof setInterval> | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  // ── Load .txt file ─────────────────────────────────────────────────────────
  const handleFile = (e: React.ChangeEvent<HTMLInputElement>) => {
    const f = e.target.files?.[0];
    if (!f) return;
    const reader = new FileReader();
    reader.onload = ev => {
      const text = ev.target?.result as string;
      setUrlInput(text);
      const parsed = parseUrls(text);
      toast.success(`Loaded ${parsed.length} URLs from ${f.name}`);
    };
    reader.readAsText(f);
    e.target.value = '';
  };

  // ── Parse input ────────────────────────────────────────────────────────────
  const handleLoad = () => {
    const parsed = parseUrls(urlInput);
    if (parsed.length === 0) { toast.error('No valid URLs found. Each URL must start with http:// or https://'); return; }
    setUrls(parsed);
    setResults(new Map());
    toast.success(`${parsed.length} URLs loaded — ready to scan`);
  };

  // ── Start scan ─────────────────────────────────────────────────────────────
  const startScan = useCallback(async () => {
    if (urls.length === 0) { toast.error('Load URLs first'); return; }

    abortRef.current = new AbortController();
    const signal = abortRef.current.signal;

    setPhase('running');
    setCurrentIdx(0);
    setResults(new Map());
    const t0 = Date.now();
    setStartTime(t0);

    // Start elapsed timer
    timerRef.current = setInterval(() => setElapsed(Date.now() - t0), 500);

    // Initialize all as pending
    const initMap = new Map<string, UrlResult>();
    for (const url of urls) {
      initMap.set(url, {
        url, status: 'pending', vulnerable: false,
        paramCount: 0, vulnParams: [], totalHits: 0, duration: 0, severity: 'none',
      });
    }
    setResults(new Map(initMap));

    // Semaphore queue
    let idx = 0;
    const workers = Array.from({ length: Math.min(concurrency, urls.length) }, async () => {
      while (true) {
        if (signal.aborted) break;
        const myIdx = idx++;
        if (myIdx >= urls.length) break;

        const url = urls[myIdx];
        setCurrentIdx(myIdx);

        // Mark scanning
        setResults(prev => {
          const next = new Map(prev);
          next.set(url, { ...next.get(url)!, status: 'scanning' });
          return next;
        });

        const urlStart = Date.now();
        const vulnParams: ParamHit[] = [];
        let totalHits = 0;
        let severity = 'none';
        let paramCount = 0;

        try {
          await scanUrlStream(url, signal, (ev) => {
            if (ev.type === 'scan_start') {
              paramCount = (ev.totalParams as number) ?? 0;
            }
            if (ev.type === 'param_done' && ev.vulnerable) {
              const hit: ParamHit = {
                param: ev.param as string,
                severity: ev.severity as string,
                hitsCount: (ev.hitsCount as number) ?? 0,
                injectionContext: (ev.injectionContext as string) ?? null,
                bestPocUrl: (ev.bestPocUrl as string) ?? '',
              };
              vulnParams.push(hit);
              totalHits += hit.hitsCount;
              if ((SEV_RANK[hit.severity] ?? 0) > (SEV_RANK[severity] ?? 0)) severity = hit.severity;
            }
          });

          setResults(prev => {
            const next = new Map(prev);
            next.set(url, {
              url, status: 'done',
              vulnerable: vulnParams.length > 0,
              paramCount, vulnParams, totalHits, severity,
              duration: Date.now() - urlStart,
            });
            return next;
          });
        } catch (err) {
          if (signal.aborted) {
            setResults(prev => {
              const next = new Map(prev);
              next.set(url, { ...next.get(url)!, status: 'skipped' });
              return next;
            });
            break;
          }
          setResults(prev => {
            const next = new Map(prev);
            next.set(url, {
              url, status: 'error',
              error: (err as Error).message,
              vulnerable: false, paramCount: 0, vulnParams: [], totalHits: 0, severity: 'none',
              duration: Date.now() - urlStart,
            });
            return next;
          });
        }
      }
    });

    await Promise.all(workers);

    if (timerRef.current) clearInterval(timerRef.current);
    setElapsed(Date.now() - t0);
    setPhase('done');
  }, [urls, concurrency]);

  // ── Stop scan ──────────────────────────────────────────────────────────────
  const stopScan = () => {
    abortRef.current?.abort();
    if (timerRef.current) clearInterval(timerRef.current);
    setPhase('done');
    toast.info('Scan stopped');
  };

  // ── Export ─────────────────────────────────────────────────────────────────
  const exportCsv = () => {
    const csv = buildCsv([...results.values()]);
    const blob = new Blob([csv], { type: 'text/csv' });
    const a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = 'bulk-scan.csv'; a.click();
    toast.success('CSV downloaded');
  };

  const exportMd = () => {
    const res = [...results.values()];
    const vuln = res.filter(r => r.vulnerable).length;
    const md = buildMarkdown(res, { total: res.length, vuln, duration: elapsed });
    const blob = new Blob([md], { type: 'text/markdown' });
    const a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = 'bulk-scan-report.md'; a.click();
    toast.success('Report downloaded');
  };

  const copyPoc = (url: string, i: number) => {
    navigator.clipboard.writeText(url);
    setCopiedIdx(i);
    setTimeout(() => setCopiedIdx(null), 2000);
    toast.success('PoC URL copied');
  };

  const toggleExpand = (url: string) => {
    setExpandedUrls(prev => {
      const next = new Set(prev);
      next.has(url) ? next.delete(url) : next.add(url);
      return next;
    });
  };

  // ── Stats ──────────────────────────────────────────────────────────────────
  const allResults = [...results.values()];
  const done       = allResults.filter(r => r.status === 'done' || r.status === 'error').length;
  const vulnCount  = allResults.filter(r => r.vulnerable).length;
  const displayed  = filterVuln ? allResults.filter(r => r.vulnerable) : allResults;
  const progress   = urls.length > 0 ? (done / urls.length) * 100 : 0;

  return (
    <div className="flex flex-col h-full bg-background">
      {/* Header */}
      <div className="p-6 border-b border-border bg-card/50 flex items-center justify-between shrink-0">
        <div>
          <div className="flex items-center gap-2 mb-0.5">
            <List className="w-5 h-5 text-primary" />
            <h2 className="text-xl font-bold tracking-tight">Bulk XSS Scanner</h2>
            <span className="text-[9px] px-1.5 py-0.5 rounded bg-primary/20 text-primary font-bold uppercase tracking-wider">MASS SCAN</span>
          </div>
          <p className="text-xs text-muted-foreground">Upload a .txt file or paste URLs — one per line. Scans all concurrently for XSS vulnerabilities.</p>
        </div>
        {phase === 'done' && allResults.length > 0 && (
          <div className="flex items-center gap-2">
            <button onClick={exportCsv} className="flex items-center gap-1.5 px-3 py-1.5 border border-border hover:border-primary text-xs font-bold rounded transition-colors">
              <Download className="w-3.5 h-3.5" /> CSV
            </button>
            <button onClick={exportMd} className="flex items-center gap-1.5 px-3 py-1.5 bg-primary text-primary-foreground hover:bg-primary/90 text-xs font-bold rounded transition-colors">
              <Download className="w-3.5 h-3.5" /> Report .md
            </button>
          </div>
        )}
      </div>

      <div className="flex flex-1 overflow-hidden">
        {/* Left panel: input */}
        <div className="w-80 border-r border-border flex flex-col shrink-0">
          <div className="p-4 border-b border-border space-y-3">
            {/* File upload */}
            <div>
              <label className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground block mb-1.5">Upload .txt file</label>
              <input ref={fileInputRef} type="file" accept=".txt" className="hidden" onChange={handleFile} />
              <button
                onClick={() => fileInputRef.current?.click()}
                className="w-full flex items-center justify-center gap-2 py-3 border-2 border-dashed border-border hover:border-primary text-xs font-semibold rounded transition-colors text-muted-foreground hover:text-primary"
              >
                <Upload className="w-4 h-4" /> Upload URLs.txt
              </button>
            </div>

            <div className="flex items-center gap-2">
              <div className="h-px flex-1 bg-border" />
              <span className="text-[10px] text-muted-foreground uppercase">or paste</span>
              <div className="h-px flex-1 bg-border" />
            </div>

            {/* Textarea */}
            <textarea
              value={urlInput}
              onChange={e => setUrlInput(e.target.value)}
              placeholder={"https://target1.com/page?q=test\nhttps://target2.com/search?id=1\nhttps://target3.com/page?name=a"}
              className="w-full h-36 bg-background border border-border rounded px-3 py-2 text-[11px] font-mono resize-none focus:outline-none focus:ring-1 focus:ring-primary placeholder:text-muted-foreground/40 leading-relaxed"
            />

            <button
              onClick={handleLoad}
              disabled={phase === 'running'}
              className="w-full py-2 border border-primary text-primary hover:bg-primary/10 text-xs font-bold rounded transition-colors flex items-center justify-center gap-2 disabled:opacity-40"
            >
              <FileText className="w-3.5 h-3.5" /> Parse URLs
            </button>

            {urls.length > 0 && (
              <div className="text-[11px] text-primary font-mono text-center">
                {urls.length} URL{urls.length !== 1 ? 's' : ''} ready
              </div>
            )}
          </div>

          {/* Concurrency setting */}
          <div className="p-4 border-b border-border space-y-2">
            <label className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground block">
              Concurrency (parallel scans)
            </label>
            <div className="flex items-center gap-3">
              <input
                type="range" min={1} max={10} value={concurrency}
                onChange={e => setConcurrency(Number(e.target.value))}
                className="flex-1 accent-primary h-1"
                disabled={phase === 'running'}
              />
              <span className="text-primary font-mono text-sm font-bold w-4">{concurrency}</span>
            </div>
            <p className="text-[10px] text-muted-foreground">Higher = faster but more aggressive. Use 1-3 for stealth.</p>
          </div>

          {/* Action button */}
          <div className="p-4">
            {phase !== 'running' ? (
              <button
                onClick={startScan}
                disabled={urls.length === 0}
                className="w-full py-3 bg-primary text-primary-foreground font-bold rounded flex items-center justify-center gap-2 hover:bg-primary/90 transition-colors disabled:opacity-40 disabled:cursor-not-allowed"
              >
                <Play className="w-4 h-4" /> Start Bulk Scan
              </button>
            ) : (
              <button
                onClick={stopScan}
                className="w-full py-3 bg-destructive/20 border border-destructive/40 text-destructive font-bold rounded flex items-center justify-center gap-2 hover:bg-destructive/30 transition-colors"
              >
                <Square className="w-4 h-4" /> Stop Scan
              </button>
            )}
          </div>

          {/* URL list preview */}
          {urls.length > 0 && (
            <div className="flex-1 overflow-y-auto px-3 pb-3">
              <div className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground mb-2">URL Queue</div>
              <div className="space-y-1">
                {urls.map((u, i) => {
                  const r = results.get(u);
                  return (
                    <div key={i} className="flex items-center gap-2 text-[10px] font-mono">
                      <span className="w-4 text-right text-muted-foreground/40 shrink-0">{i + 1}</span>
                      {r?.status === 'scanning' && <Loader className="w-2.5 h-2.5 text-primary animate-spin shrink-0" />}
                      {r?.status === 'done' && r.vulnerable && <AlertTriangle className="w-2.5 h-2.5 text-red-400 shrink-0" />}
                      {r?.status === 'done' && !r.vulnerable && <CheckCircle className="w-2.5 h-2.5 text-green-500 shrink-0" />}
                      {r?.status === 'error' && <AlertTriangle className="w-2.5 h-2.5 text-yellow-400 shrink-0" />}
                      {(!r || r.status === 'pending') && <Clock className="w-2.5 h-2.5 text-muted-foreground/30 shrink-0" />}
                      <span className="text-muted-foreground truncate">{new URL(u).hostname + new URL(u).pathname}</span>
                    </div>
                  );
                })}
              </div>
            </div>
          )}
        </div>

        {/* Right panel: results */}
        <div className="flex-1 flex flex-col overflow-hidden">
          {/* Stats bar */}
          {(phase === 'running' || phase === 'done') && (
            <div className="border-b border-border bg-card/30 px-6 py-3 flex items-center gap-8 shrink-0">
              <div className="flex items-center gap-4 flex-1">
                {/* Progress bar */}
                <div className="flex-1 h-1 bg-secondary rounded-full overflow-hidden">
                  <motion.div
                    className="h-full bg-primary rounded-full"
                    initial={{ width: 0 }}
                    animate={{ width: `${progress}%` }}
                    transition={{ ease: 'linear' }}
                  />
                </div>
                <span className="text-[10px] font-mono text-muted-foreground shrink-0">
                  {done}/{urls.length}
                </span>
              </div>

              <div className="flex items-center gap-6 text-[11px] font-mono">
                <span className="text-muted-foreground">Time: <span className="text-foreground">{(elapsed / 1000).toFixed(1)}s</span></span>
                <span className="text-red-400 font-bold">{vulnCount} VULN</span>
                <span className="text-green-500">{done - vulnCount} SAFE</span>
                {phase === 'running' && <Loader className="w-3.5 h-3.5 text-primary animate-spin" />}
                {phase === 'done' && <CheckCircle className="w-3.5 h-3.5 text-primary" />}
              </div>

              {/* Filter */}
              <button
                onClick={() => setFilterVuln(v => !v)}
                className={`flex items-center gap-1.5 px-2.5 py-1 rounded border text-[10px] font-bold transition-colors ${
                  filterVuln ? 'border-red-500/50 bg-red-500/10 text-red-400' : 'border-border text-muted-foreground hover:border-border/80'
                }`}
              >
                <Filter className="w-3 h-3" /> Vuln only
              </button>
            </div>
          )}

          {/* Results list */}
          <div className="flex-1 overflow-y-auto p-4 space-y-2">
            {phase === 'idle' && (
              <div className="flex flex-col items-center justify-center h-full text-center">
                <Target className="w-16 h-16 text-primary/10 mb-4 stroke-1" />
                <p className="text-muted-foreground font-mono text-sm">Upload or paste URLs, then click Start</p>
                <p className="text-muted-foreground/40 font-mono text-xs mt-1">One URL per line · http:// or https:// required</p>
              </div>
            )}

            <AnimatePresence initial={false}>
              {displayed.map((r, i) => {
                const isExpanded = expandedUrls.has(r.url);
                return (
                  <motion.div
                    key={r.url}
                    initial={{ opacity: 0, y: 4 }}
                    animate={{ opacity: 1, y: 0 }}
                    className={`border rounded-lg overflow-hidden transition-colors ${
                      r.vulnerable ? 'border-red-500/20' : 'border-border'
                    }`}
                  >
                    {/* Row header */}
                    <div
                      className={`flex items-center gap-3 px-4 py-3 cursor-pointer hover:bg-card/60 transition-colors ${
                        r.vulnerable ? 'bg-red-500/5' : 'bg-card/20'
                      }`}
                      onClick={() => r.status === 'done' && toggleExpand(r.url)}
                    >
                      {/* Status icon */}
                      <div className="shrink-0">
                        {r.status === 'scanning' && <Loader className="w-4 h-4 text-primary animate-spin" />}
                        {r.status === 'done' && r.vulnerable && <AlertTriangle className="w-4 h-4 text-red-400" />}
                        {r.status === 'done' && !r.vulnerable && <CheckCircle className="w-4 h-4 text-green-500" />}
                        {r.status === 'error' && <AlertTriangle className="w-4 h-4 text-yellow-400" />}
                        {r.status === 'pending' && <Clock className="w-4 h-4 text-muted-foreground/30" />}
                        {r.status === 'skipped' && <Clock className="w-4 h-4 text-muted-foreground/20" />}
                      </div>

                      {/* URL */}
                      <span className="font-mono text-[11px] text-foreground flex-1 truncate">{r.url}</span>

                      {/* Badges */}
                      <div className="flex items-center gap-2 shrink-0">
                        {r.status === 'done' && (
                          <>
                            {r.vulnerable && (
                              <span className={`text-[9px] font-bold px-1.5 py-0.5 rounded border ${sevColor(r.severity)}`}>
                                {r.severity.toUpperCase()}
                              </span>
                            )}
                            {r.vulnParams.length > 0 && (
                              <span className="text-[9px] font-mono text-red-400">
                                {r.vulnParams.length} param{r.vulnParams.length !== 1 ? 's' : ''}
                              </span>
                            )}
                            <span className="text-[9px] font-mono text-muted-foreground">{r.duration}ms</span>
                          </>
                        )}
                        {r.status === 'error' && <span className="text-[9px] text-yellow-400 font-mono">ERROR</span>}
                        {r.status === 'done' && (
                          isExpanded
                            ? <ChevronUp className="w-3.5 h-3.5 text-muted-foreground" />
                            : <ChevronDown className="w-3.5 h-3.5 text-muted-foreground" />
                        )}
                      </div>
                    </div>

                    {/* Expanded detail */}
                    <AnimatePresence>
                      {isExpanded && r.status === 'done' && (
                        <motion.div
                          initial={{ height: 0, opacity: 0 }}
                          animate={{ height: 'auto', opacity: 1 }}
                          exit={{ height: 0, opacity: 0 }}
                          className="overflow-hidden"
                        >
                          <div className="px-4 py-3 border-t border-border bg-secondary/10 space-y-3">
                            {r.vulnParams.length === 0 ? (
                              <p className="text-[11px] text-muted-foreground font-mono">
                                {r.paramCount === 0
                                  ? 'No query parameters found in this URL.'
                                  : `${r.paramCount} parameter${r.paramCount !== 1 ? 's' : ''} tested — no XSS detected.`}
                              </p>
                            ) : (
                              <div className="space-y-2">
                                <div className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground">
                                  Vulnerable Parameters ({r.vulnParams.length})
                                </div>
                                {r.vulnParams.map((p, pi) => (
                                  <div key={pi} className="rounded-lg border border-red-500/20 bg-red-500/5 p-3 space-y-1.5">
                                    <div className="flex items-center gap-2">
                                      <span className="font-mono text-[11px] text-primary font-bold">{p.param}</span>
                                      <span className={`text-[9px] font-bold px-1.5 py-0.5 rounded border ${sevColor(p.severity)}`}>
                                        {p.severity.toUpperCase()}
                                      </span>
                                      {p.injectionContext && (
                                        <span className="text-[9px] text-muted-foreground font-mono">{p.injectionContext}</span>
                                      )}
                                      <span className="text-[9px] text-muted-foreground font-mono ml-auto">{p.hitsCount} hit{p.hitsCount !== 1 ? 's' : ''}</span>
                                    </div>
                                    {p.bestPocUrl && (
                                      <div className="flex items-center gap-2">
                                        <code className="text-[10px] font-mono text-primary/70 bg-secondary/40 rounded px-2 py-1 flex-1 truncate border border-border/40">
                                          {p.bestPocUrl}
                                        </code>
                                        <button
                                          onClick={() => copyPoc(p.bestPocUrl, i * 100 + pi)}
                                          className="shrink-0 p-1.5 rounded border border-border hover:border-primary text-muted-foreground hover:text-primary transition-colors"
                                        >
                                          {copiedIdx === i * 100 + pi ? <Check className="w-3 h-3 text-primary" /> : <Copy className="w-3 h-3" />}
                                        </button>
                                      </div>
                                    )}
                                  </div>
                                ))}
                              </div>
                            )}
                            {r.error && (
                              <p className="text-[11px] text-yellow-400 font-mono">{r.error}</p>
                            )}
                          </div>
                        </motion.div>
                      )}
                    </AnimatePresence>
                  </motion.div>
                );
              })}
            </AnimatePresence>
          </div>
        </div>
      </div>
    </div>
  );
}
